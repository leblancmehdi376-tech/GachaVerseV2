export interface NamedMove { name: string; ability: string; icon?: string }
export interface CharacterKit { role: NakimeRole; moves: NamedMove[] }

const parsed = new Map<string, CharacterKit>();
for (const [id, raw] of Object.entries(K)) {
  const [role, ...moves] = raw.split('|');
  parsed.set(id, {
    role: role as NakimeRole,
    moves: moves.map(m => {
      const [name, ability, icon] = m.split('@');
      return { name, ability, ...(icon ? { icon } : {}) };
    }),
  });
}

/** Kit nommé d'un personnage (rôle + techniques), s'il en a un. */
export function getCharacterKit(templateId: string): CharacterKit | undefined {
  return parsed.get(templateId);
}

